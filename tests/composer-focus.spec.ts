import { expect, test } from '@playwright/test'

test.use({ reducedMotion: 'reduce' })

test.beforeEach(async ({ page }) => {
  await page.route('**/query', (route) => route.fulfill({ json: { rows: [] } }))
  await page.goto('/')
  await expect(page.locator('.monaco-editor')).toBeVisible()
})

test('choosing an action and pressing Escape return focus to the prompt', async ({ page }) => {
  const input = page.getByRole('textbox', { name: 'Ask the SQL assistant' })
  const selector = page.getByRole('button', { name: /Assistant action:/ })
  await input.fill('Help with this query')
  await selector.click()
  await expect(page.locator('.assistant-composer')).toHaveCSS('width', '460px')
  await page.getByRole('menuitem', { name: /Explain SQL/ }).click()
  await expect(input).toBeFocused()
  await expect(input).toHaveValue('Help with this query')
  await expect(input).toHaveAttribute('placeholder', 'Explain this SQL…')
  await selector.click()
  await page.keyboard.press('Escape')
  await expect(input).toBeFocused()
  await expect(page.getByRole('menu')).toHaveCount(0)
})

test('the selector supports keyboard navigation and the voice button stays in the same focus group', async ({ page }) => {
  const input = page.getByRole('textbox', { name: 'Ask the SQL assistant' })
  const selector = page.getByRole('button', { name: /Assistant action:/ })
  await input.focus()
  await page.keyboard.press('Tab')
  await expect(selector).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('menu')).toBeVisible()
  await page.keyboard.press('End')
  await expect(page.getByRole('menuitem', { name: /Improve SQL/ })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(input).toBeFocused()
  await expect(selector).toHaveAttribute('aria-label', 'Assistant action: Improve')
  await page.keyboard.press('Tab')
  await expect(selector).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Start voice input' })).toBeFocused()
  await expect(page.locator('.assistant-composer')).toHaveCSS('width', '460px')
})

test('clicking outside the menu focuses the clicked control without a second click', async ({ page }) => {
  const input = page.getByRole('textbox', { name: 'Ask the SQL assistant' })
  const selector = page.getByRole('button', { name: /Assistant action:/ })
  await selector.click()
  await input.click()
  await expect(input).toBeFocused()
  await expect(page.getByRole('menu')).toHaveCount(0)
  await selector.click()
  await page.getByRole('button', { name: 'Dark mode', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Dark mode', exact: true })).toBeFocused()
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect(page.locator('.assistant-composer')).toHaveCSS('width', '380px')
})
